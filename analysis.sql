-- 1. Customer order details
SELECT
    c.customer_name,
    o.order_id,
    p.product_name,
    o.quantity
FROM orders o
JOIN customers c
    ON o.customer_id = c.customer_id
JOIN products p
    ON o.product_id = p.product_id;


-- 2. Total spending per customer
SELECT
    c.customer_name,
    SUM(p.price * o.quantity) AS total_spending
FROM orders o
JOIN products p
    ON o.product_id = p.product_id
JOIN customers c
    ON o.customer_id = c.customer_id
GROUP BY c.customer_name;


-- 3. Customers spending more than 30000
SELECT
    c.customer_name,
    SUM(p.price * o.quantity) AS total_expense
FROM orders o
JOIN products p
    ON o.product_id = p.product_id
JOIN customers c
    ON o.customer_id = c.customer_id
GROUP BY c.customer_name
HAVING SUM(p.price * o.quantity) > 30000
ORDER BY total_expense DESC;
--Calculate the total revenue generated by the e-commerce business for each month.---
SELECT
    DATE_TRUNC('month', o.order_date) AS sales_month,
    SUM(p.price * o.quantity) AS revenue
FROM orders o
JOIN products p
    ON o.product_id = p.product_id
GROUP BY DATE_TRUNC('month', o.order_date)
ORDER BY sales_month;
--Find the total quantity sold for each product.--
select p.product_name,sum(o.quantity) as Total_quantity 
from orders o
join products p 
on o.product_id = p.product_id
group by p.product_name
order by Total_quantity desc;
--Find the top 3 customers who spent the most money--
select c.customer_name,SUM(p.price * o.quantity) AS Money_spent
from orders o
join products p 
on o.product_id = p.product_id
join customers c 
on o.customer_id = c.customer_id
group  by c.customer_name
order by Money_spent desc
limit 3;
--Calculate the average value of an order--.
select SUM(p.price * o.quantity) AS Total_revenue,count(o.order_id) as Total_order,
ROUND(
        SUM(p.price * o.quantity) / COUNT(o.order_id),
        2
    ) AS average_order_value
from orders o
join products p 
on o.product_id = p.product_id
--Find customers who have placed more than one order--
select c.customer_name,count(o.order_id) 
from orders o
join products p 
on o.product_id = p.product_id
join customers c 
on o.customer_id = c.customer_id
group by c.customer_name
having count(o.order_id)>1
