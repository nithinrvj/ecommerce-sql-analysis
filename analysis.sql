WITH customer_spending AS (
    SELECT
        c.customer_name,
        SUM(p.price * o.quantity) AS money_spent
    FROM orders o
    JOIN products p
        ON o.product_id = p.product_id
    JOIN customers c
        ON o.customer_id = c.customer_id
    GROUP BY c.customer_id, c.customer_name
),
ranked_customers AS (
    SELECT
        customer_name,
        money_spent,
        DENSE_RANK() OVER (ORDER BY money_spent DESC) AS rnk
    FROM customer_spending
)
SELECT customer_name, money_spent
FROM ranked_customers
WHERE rnk = 2;
